-- Sân vận động / nhà hát
CREATE TABLE venues (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name        VARCHAR(200) NOT NULL,
                        address     VARCHAR(500) NOT NULL,
                        capacity    INT          NOT NULL CHECK (capacity > 0),
                        created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Một trận đấu hoặc một show
CREATE TABLE events (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        venue_id    BIGINT       NOT NULL REFERENCES venues (id),
                        name        VARCHAR(200) NOT NULL,
                        type        VARCHAR(20)  NOT NULL CHECK (type IN ('MATCH', 'CONCERT')),
                        starts_at   TIMESTAMPTZ  NOT NULL,
                        status      VARCHAR(20)  NOT NULL DEFAULT 'DRAFT'
                            CHECK (status IN ('DRAFT', 'ON_SALE', 'ENDED')),
                        created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Trang chủ hay lọc "sự kiện đang mở bán, sắp diễn ra"
CREATE INDEX idx_events_status_starts_at ON events (status, starts_at);

-- Khu khán đài của một sự kiện, mỗi khu một giá
CREATE TABLE sections (
                          id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          event_id      BIGINT        NOT NULL REFERENCES events (id) ON DELETE CASCADE,
                          name          VARCHAR(100)  NOT NULL,
                          seating_type  VARCHAR(20)   NOT NULL CHECK (seating_type IN ('NUMBERED', 'GENERAL')),
                          capacity      INT           NOT NULL CHECK (capacity > 0),
                          price         NUMERIC(12,2) NOT NULL CHECK (price >= 0),
                          UNIQUE (event_id, name)
);