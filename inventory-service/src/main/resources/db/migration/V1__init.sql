-- Ghế có số, dành cho khu NUMBERED. Mỗi dòng là MỘT chiếc ghế.
CREATE TABLE seats (
                       id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       event_id     BIGINT      NOT NULL,   -- id bên event-service, KHÔNG phải khoá ngoại
                       section_id   BIGINT      NOT NULL,   -- id bên event-service, KHÔNG phải khoá ngoại
                       seat_row     INT         NOT NULL CHECK (seat_row > 0),
                       seat_number  INT         NOT NULL CHECK (seat_number > 0),
                       status       VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
                           CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD')),
                       UNIQUE (section_id, seat_row, seat_number)
);

-- Xem sơ đồ ghế / đếm ghế trống luôn lọc theo sự kiện và trạng thái
CREATE INDEX idx_seats_event_status ON seats (event_id, status);

-- Vé đứng, dành cho khu GENERAL: không cần từng ghế, chỉ cần ĐẾM
CREATE TABLE section_stocks (
                                section_id  BIGINT PRIMARY KEY,      -- id bên event-service
                                event_id    BIGINT NOT NULL,
                                total       INT    NOT NULL CHECK (total > 0),
                                remaining   INT    NOT NULL CHECK (remaining >= 0 AND remaining <= total)
);